
from __future__ import annotations

import json
import pandas as pd
import math
from pathlib import Path
from typing import Annotated

import joblib
import numpy as np
import torch
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, ConfigDict, Field

from nids.models.train_model import NIDSClassifier


ROOT = Path(__file__).resolve().parents[3]
ARTIFACT_DIR = ROOT / "artifacts"
MODEL_PATH = ARTIFACT_DIR / "nids_model.pt"
PREPROCESSOR_PATH = ARTIFACT_DIR / "preprocessor.joblib"
METADATA_PATH = ARTIFACT_DIR / "metadata.json"

app = FastAPI(
    title="AI-NIDS API",
    description="Network-flow attack classification service",
    version="1.0.0",
)

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model = None
preprocessor = None
metadata = None
classes = []
feature_columns = []


class FlowRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    features: dict[str, float]


class PredictionResponse(BaseModel):
    predicted_class: str
    confidence: float
    probabilities: dict[str, float]
    model_version: str = "1.0.0"


@app.on_event("startup")
def load_artifacts() -> None:
    global model, preprocessor, metadata, classes, feature_columns

    required = [MODEL_PATH, PREPROCESSOR_PATH, METADATA_PATH]
    missing = [str(path) for path in required if not path.is_file()]
    if missing:
        raise RuntimeError(
            "Missing model artifacts: " + ", ".join(missing)
        )

    metadata = json.loads(METADATA_PATH.read_text(encoding="utf-8"))
    classes = metadata["classes"]
    feature_columns = metadata["feature_columns"]

    if len(classes) < 2 or not feature_columns:
        raise RuntimeError("Invalid model metadata.")

    # Only load artifacts generated by this trusted project.
    checkpoint = torch.load(
        MODEL_PATH,
        map_location=device,
        weights_only=True,
    )

    model = NIDSClassifier(
        input_dim=int(checkpoint["input_dim"]),
        num_classes=len(classes),
    ).to(device)
    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()

    preprocessor = joblib.load(PREPROCESSOR_PATH)


@app.get("/health")
def health():
    return {
        "status": "ready" if model is not None else "not_ready",
        "device": str(device),
        "classes": len(classes),
        "features": len(feature_columns),
    }


@app.post("/predict", response_model=PredictionResponse)
def predict(request: FlowRequest):
    if model is None or preprocessor is None:
        raise HTTPException(
            status_code=503,
            detail="Model artifacts are not loaded.",
        )

    supplied = request.features
    expected = set(feature_columns)
    actual = set(supplied)

    missing = sorted(expected - actual)
    extra = sorted(actual - expected)

    if missing or extra:
        raise HTTPException(
            status_code=422,
            detail={
                "message": "Feature schema mismatch",
                "missing_features": missing,
                "unexpected_features": extra,
            },
        )

    values = []
    for name in feature_columns:
        value = supplied[name]

        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise HTTPException(
                status_code=422,
                detail=f"Feature {name!r} must be numeric.",
            )

        if not math.isfinite(value):
            raise HTTPException(
                status_code=422,
                detail=f"Feature {name!r} must be finite.",
            )

        values.append(float(value))

    
    try:
        import pandas as pd

        raw = pd.DataFrame([values], columns=feature_columns)
        transformed = preprocessor.transform(raw).astype(np.float32)

        if not np.isfinite(transformed).all():
            raise ValueError("Transformed features are not finite.")

        with torch.inference_mode():
            tensor = torch.from_numpy(transformed).to(device)
            logits = model(tensor)
            probabilities = (
                torch.softmax(logits, dim=1)[0].cpu().numpy()
            )

        index = int(np.argmax(probabilities))

        return PredictionResponse(
            predicted_class=classes[index],
            confidence=float(probabilities[index]),
            probabilities={
                label: float(probabilities[i])
                for i, label in enumerate(classes)
            },
        )

    except HTTPException:
        raise
    except (ValueError, RuntimeError) as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Inference failed: {exc}",
        ) from exc

